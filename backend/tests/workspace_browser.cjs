const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const output = process.env.SUITE_UI_OUTPUT || path.resolve(__dirname, '../../outputs/workspace-ui');
  fs.mkdirSync(output,{recursive:true});
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1600,height:1100}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto((process.env.SUITE_URL||'http://127.0.0.1:8032')+'/#dashboard');
    await page.locator('#workspaceReport iframe').waitFor();
    let view=page.frameLocator('#workspaceReport iframe');
    await view.locator('#metrics .metric-value').first().waitFor();
    await page.waitForFunction(()=>Number.parseFloat(document.querySelector('#workspaceReport iframe').style.height)>500);
    assert.equal(await view.locator('.metric').count(),25);
    assert.equal(await page.locator('#platformSidebar').evaluate(el=>Math.round(el.getBoundingClientRect().width)),224);
    const bounds=await view.locator('body').evaluate(b=>({height:Math.ceil(b.getBoundingClientRect().height),overflow:document.documentElement.scrollWidth>innerWidth}));
    const frameHeight=await page.locator('#workspaceReport iframe').evaluate(f=>f.getBoundingClientRect().height);
    assert(Math.abs(bounds.height-frameHeight)<5,'Full report must expand without an internal vertical scroll area');
    assert.equal(bounds.overflow,false);
    const pixelCheck=()=>view.locator('canvas').evaluate(c=>{
      const a=c.getContext('2d').getImageData(0,0,c.width,c.height).data;
      let count=0;for(let i=0;i<a.length;i+=4) if(a[i+3]&&Math.max(a[i],a[i+1],a[i+2])-Math.min(a[i],a[i+1],a[i+2])>80) count++;
      return count;
    });
    const chartPixels=await pixelCheck();
    assert(chartPixels>100);
    await page.screenshot({path:path.join(output,'workbench-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);
    await page.screenshot({path:path.join(output,'workbench-mobile.png'),fullPage:true});
    assert(await view.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.setViewportSize({width:1600,height:1100});
    await page.click('#workspaceNew');
    await page.check('#sqDemo');
    await page.fill('#sp_total_requests','40');
    await page.fill('#sqConcurrency','2');
    await page.fill('#sqInput','128');
    await page.fill('#sqOutput','16');
    await page.getByRole('button',{name:'预览计划',exact:true}).click();
    await page.click('#suiteExecute');
    await page.waitForSelector('#workspaceReport iframe');
    view=page.frameLocator('#workspaceReport iframe');
    await view.locator('#requests tbody tr').first().waitFor();
    const before=await view.locator('#requests tbody tr').count();
    assert.equal(await view.locator('#status').textContent(),'运行中');
    await page.locator('#workspaceReport iframe').evaluate(f=>{f.dataset.stableFrame='true';});
    await view.locator('#requests tbody tr').nth(before).waitFor({timeout:10000});
    const after=await view.locator('#requests tbody tr').count();
    assert(after>before,'Live chart must receive new request samples');
    assert.equal(await page.locator('#workspaceReport iframe').getAttribute('data-stable-frame'),'true','Polling must preserve the report frame');
    await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
    await page.screenshot({path:path.join(output,'workbench-live.png'),fullPage:true});
    await page.click('#workspaceCancel');
    await view.locator('#status').filter({hasText:'已取消'}).waitFor({timeout:15000});
    await view.locator('[data-series="latency_ms"]').uncheck();
    const noLatency=await pixelCheck();
    await view.locator('[data-series="latency_ms"]').check();
    assert.notEqual(await pixelCheck(),noLatency,'Legend must toggle plotted series');
    await view.locator('canvas').hover({position:{x:150,y:80}});
    assert(await view.locator('#chart-tooltip').isVisible());
    const dl=page.waitForEvent('download');
    await view.locator('#export-json').click();
    await (await dl).saveAs(path.join(output,'live-report.json'));
    const exported=JSON.parse(fs.readFileSync(path.join(output,'live-report.json'),'utf8'));
    assert.equal(exported.status,'cancelled');
    assert(exported.requests.length>0&&exported.requests.length<40);
    await page.locator('#nav summary').click();
    await page.getByRole('button',{name:'中转站',exact:true}).click();
    await page.getByRole('heading',{name:/中转站/}).first().waitFor();
    assert.equal(await page.locator('#nav button.active').textContent(),'中转站');
    assert.deepEqual(errors,[]);
    const result={ok:true,metrics:25,chartPixels,liveSamplesBefore:before,liveSamplesAfter:after,cancelledSamples:exported.requests.length,errors};
    fs.writeFileSync(path.join(output,'workspace-verification.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result));
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
